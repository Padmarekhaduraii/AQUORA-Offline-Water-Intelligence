"""
=============================================================================
AQUORA - Physical Telemetry Test Simulator
=============================================================================
Simulates field LoRa packet transmission for testing and local demonstration.
NOTE: Per AQUORA governance principles, all data generated by this tool is
explicitly tagged with:
  "is_simulated": True
and stored as simulated in the SQLite database and dashboard.
=============================================================================
"""

import time
import argparse
import json
from datetime import datetime, timezone, timedelta
import urllib.request
import urllib.error

DEFAULT_URL = "http://127.0.0.1:8000/api/v1/sensors/ingest"
DEFAULT_KEY = "aquora_live_lora_secret_key_2026"

def send_reading(node_id: str, level_cm: float, battery: float, timestamp: datetime, url: str, key: str):
    payload = {
        "node_id": node_id,
        "timestamp_recorded": timestamp.isoformat(),
        "water_level_cm": round(level_cm, 2),
        "water_flow_rate_lps": round(level_cm * 6.5, 1),
        "battery_voltage": round(battery, 2),
        "rssi_dbm": -74.0,
        "snr_db": 9.2,
        "is_simulated": True  # Explicitly labeled as simulated
    }

    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={
            "Content-Type": "application/json",
            "X-API-Key": key
        },
        method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            print(f"[TEST-INJECT] Sent reading for {node_id} @ {level_cm} cm (HTTP {resp.status}) [SIMULATED]")
            return True
    except urllib.error.HTTPError as e:
        print(f"[TEST-ERR] HTTP Error {e.code}: {e.read().decode('utf-8', 'ignore')}")
    except Exception as e:
        print(f"[TEST-ERR] Connection failed: {e}")
    return False


def run_scenario_surge(url: str, key: str):
    """
    Simulates physical sluice gate opening at Grand Anicut Head:
    1. Upstream node was dry (8 cm)
    2. Sluice opened -> water jumps to 65 cm, then 82 cm
    3. Downstream node is currently dry (4 cm) awaiting wave arrival
    """
    print("\n--- Running Scenario: Sluice Gate Opening & Wave Propagation ---")
    now = datetime.now(timezone.utc)

    # Historical dry baseline 2 hours ago
    send_reading("NODE-UPSTREAM-01", 8.2, 4.10, now - timedelta(hours=2), url, key)
    send_reading("NODE-UPSTREAM-01", 8.5, 4.09, now - timedelta(hours=1, minutes=30), url, key)
    
    # Surge starts 45 minutes ago
    send_reading("NODE-UPSTREAM-01", 45.0, 4.08, now - timedelta(minutes=45), url, key)
    send_reading("NODE-UPSTREAM-01", 72.4, 4.07, now - timedelta(minutes=20), url, key)
    # Current active flow
    send_reading("NODE-UPSTREAM-01", 84.8, 4.06, now, url, key)

    # Downstream node is currently still dry
    send_reading("NODE-DOWNSTREAM-02", 4.1, 3.95, now - timedelta(minutes=10), url, key)
    send_reading("NODE-DOWNSTREAM-02", 4.3, 3.95, now, url, key)

    print("--- Scenario Injected: Upstream surge is active, downstream is currently dry ---")


def run_scenario_dry(url: str, key: str):
    """Simulates dry canal conditions."""
    print("\n--- Running Scenario: Completely Dry Canal ---")
    now = datetime.now(timezone.utc)
    send_reading("NODE-UPSTREAM-01", 4.2, 4.12, now - timedelta(minutes=15), url, key)
    send_reading("NODE-UPSTREAM-01", 4.1, 4.12, now, url, key)
    send_reading("NODE-DOWNSTREAM-02", 3.8, 3.98, now, url, key)
    print("--- Scenario Injected: Both nodes report dry canal bed ---")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="AQUORA Field Telemetry Simulator")
    parser.add_argument("--scenario", choices=["surge", "dry"], default="surge", help="Test scenario to inject")
    parser.add_argument("--url", default=DEFAULT_URL, help="Backend URL")
    parser.add_argument("--key", default=DEFAULT_KEY, help="Gateway API Key")

    args = parser.parse_args()
    if args.scenario == "surge":
        run_scenario_surge(args.url, args.key)
    else:
        run_scenario_dry(args.url, args.key)
