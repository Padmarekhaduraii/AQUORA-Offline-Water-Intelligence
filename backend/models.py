import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column, String, Float, Integer, Boolean, DateTime, ForeignKey, Index, Text, Enum
)
from sqlalchemy.orm import relationship

from backend.database import Base

class SensorNode(Base):
    __tablename__ = "sensor_nodes"

    id = Column(String(50), primary_key=True, index=True) # e.g. "NODE-UPSTREAM-01"
    name = Column(String(100), nullable=False)
    canal_name = Column(String(100), nullable=False, default="Cauvery Main Canal")
    reach_segment = Column(String(100), nullable=False, default="Upper Intake Reach")
    distance_from_head_km = Column(Float, nullable=False, default=0.0) # km downstream from head regulator
    latitude = Column(Float, nullable=True)
    longitude = Column(Float, nullable=True)
    zero_datum_offset_cm = Column(Float, default=0.0) # Sensor mount height above bed
    max_depth_cm = Column(Float, default=300.0) # Canal bank full depth
    is_active = Column(Boolean, default=True)
    last_seen_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    readings = relationship("SensorReading", back_populates="node", cascade="all, delete-orphan")


class SensorReading(Base):
    __tablename__ = "sensor_readings"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    node_id = Column(String(50), ForeignKey("sensor_nodes.id"), nullable=False, index=True)
    timestamp_recorded = Column(DateTime, nullable=False, index=True) # Generated by ESP32 RTC/Time
    timestamp_received = Column(DateTime, nullable=False, default=lambda: datetime.now(timezone.utc), index=True)
    water_level_cm = Column(Float, nullable=False) # Computed depth in cm
    water_flow_rate_lps = Column(Float, nullable=True) # Estimated flow rate (liters/sec)
    battery_voltage = Column(Float, nullable=True) # ESP32 battery level (e.g. 3.7 - 4.2V)
    rssi_dbm = Column(Float, nullable=True) # LoRa RSSI
    snr_db = Column(Float, nullable=True) # LoRa SNR
    reading_hash = Column(String(64), nullable=False, unique=True, index=True) # SHA-256 for deduplication
    is_simulated = Column(Boolean, default=False, index=True) # Transparently flagged if simulated for testing
    sync_status = Column(String(20), default="pending", index=True) # pending, synced, failed
    sync_tx_id = Column(String(64), nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))

    node = relationship("SensorNode", back_populates="readings")


class OfficialReservoirObservation(Base):
    __tablename__ = "official_reservoir_observations"

    id = Column(Integer, primary_key=True, autoincrement=True)
    provider_name = Column(String(50), nullable=False, index=True) # "tn_agriculture", "chennai_flood_monitor"
    reservoir_name = Column(String(100), nullable=False, index=True) # "METTUR", "BHAVANISAGAR", etc.
    observation_date = Column(String(20), nullable=False, index=True) # "2026-10-26"
    full_depth_ft = Column(Float, nullable=True)
    full_capacity_mcft = Column(Float, nullable=True)
    current_level_ft = Column(Float, nullable=True)
    current_storage_mcft = Column(Float, nullable=True)
    inflow_cusecs = Column(Float, nullable=True)
    outflow_cusecs = Column(Float, nullable=True)
    last_year_level_ft = Column(Float, nullable=True)
    last_year_storage_mcft = Column(Float, nullable=True)
    retrieved_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
    freshness_status = Column(String(20), default="FRESH") # FRESH, RECENT, STALE, UNAVAILABLE
    source_url = Column(String(255), nullable=False)
    raw_payload = Column(Text, nullable=True)


class WaterArrivalEstimate(Base):
    __tablename__ = "water_arrival_estimates"

    id = Column(Integer, primary_key=True, autoincrement=True)
    canal_name = Column(String(100), nullable=False)
    target_reach = Column(String(100), nullable=False)
    target_node_id = Column(String(50), ForeignKey("sensor_nodes.id"), nullable=True)
    reference_upstream_node_id = Column(String(50), ForeignKey("sensor_nodes.id"), nullable=True)
    status = Column(String(30), nullable=False) # SUFFICIENT_DATA, INSUFFICIENT_DATA, NO_FLOW_DETECTED, SURGE_IN_PROGRESS
    estimated_arrival_time = Column(DateTime, nullable=True)
    travel_time_hours = Column(Float, nullable=True)
    uncertainty_range_hours = Column(Float, nullable=True) # e.g. +/- 0.75 hours
    confidence_percent = Column(Float, nullable=True)
    upstream_surge_magnitude_cm = Column(Float, nullable=True)
    explanation = Column(Text, nullable=False)
    calculated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)


class IrrigationSchedule(Base):
    __tablename__ = "irrigation_schedules"

    id = Column(Integer, primary_key=True, autoincrement=True)
    zone_id = Column(String(50), nullable=False, index=True) # e.g. "ZONE-EAST-A"
    zone_name = Column(String(100), nullable=False)
    crop_type = Column(String(100), nullable=False) # e.g. "Paddy (Kuruvai)", "Paddy (Samba)", "Sugarcane"
    recommended_start = Column(DateTime, nullable=False)
    recommended_duration_minutes = Column(Integer, nullable=False)
    water_volume_liters = Column(Float, nullable=False)
    status = Column(String(20), default="PLANNED", index=True) # PLANNED, ACTIVE, COMPLETED, CANCELLED
    trigger_reason = Column(Text, nullable=False)
    offline_generated = Column(Boolean, default=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))


class SystemAlert(Base):
    __tablename__ = "system_alerts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    alert_type = Column(String(50), nullable=False, index=True) # SENSOR_DISCONNECTED, STALE_DATA, CANAL_SURGE, etc.
    severity = Column(String(20), nullable=False) # INFO, WARNING, CRITICAL
    title = Column(String(150), nullable=False)
    message = Column(Text, nullable=False)
    source_id = Column(String(50), nullable=True)
    is_acknowledged = Column(Boolean, default=False, index=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)


class SyncAuditLog(Base):
    __tablename__ = "sync_audit_log"

    id = Column(Integer, primary_key=True, autoincrement=True)
    batch_id = Column(String(64), nullable=False, index=True)
    record_type = Column(String(50), nullable=False) # "sensor_reading", "irrigation_schedule"
    record_id = Column(String(64), nullable=False)
    action = Column(String(20), nullable=False) # PUSHED, ACKNOWLEDGED, REJECTED_DUPLICATE
    status = Column(String(20), nullable=False) # SUCCESS, CONFLICT, FAILED
    error_message = Column(Text, nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))
